const data = [];
for (const skill of catalog) {
  const file = `${skill.id}.md`;
  const source = await readFile(new URL(file, root), 'utf8');
  const frontmatter = source.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
  if (!frontmatter) throw new Error(`${file}: missing YAML frontmatter`);
  const name = frontmatter[1].match(/^name:\s*(.+)$/m);
  const description = frontmatter[1].match(/^description:\s*(.+)$/m);
  if (!name || name[1].trim() !== skill.id || !description) {
    throw new Error(`${file}: name must match the filename and description is required`);
  }
  data.push({ ...skill, file, source, body: source.slice(frontmatter[0].length).trim(), lines: source.trimEnd().split('\n').length });
}

const destination = new URL('assets/skills-data.js', root);
const readme = await readFile(new URL('README.md', root), 'utf8');
// JSON string values remain data; escaping < also makes embedding safe in HTML.
const output = '// Generated by node scripts/build-site.mjs. Edit the root Markdown files instead.\n'
  + `window.MY_SKILLS = ${JSON.stringify(data, null, 2).replace(/</g, '\\u003c')};\n`
  + `window.MY_SKILLS_README = ${JSON.stringify(readme).replace(/</g, '\\u003c')};\n`;

if (args.has('--check')) {
  const existing = await readFile(destination, 'utf8').catch(() => '');
  if (existing !== output) {
    console.error('Site data is out of date. Run: node scripts/build-site.mjs');
    process.exitCode = 1;
  } else {
    console.log(`Site data matches all ${data.length} Markdown sources.`);
  }
} else {
  await writeFile(destination, output);
  console.log(`Built ${data.length} skills → ${fileURLToPath(destination)}`);
}

if (args.has('--pages')) {
  // Publish only files the page reads or offers for download.
  const staticFiles = [
    'index.html', 'README.md', '.nojekyll',
    'assets/app.js', 'assets/styles.css', 'assets/favicon.svg', 'assets/skills-data.js',
    ...data.map((skill) => skill.file),
  ];
  const contents = await Promise.all(staticFiles.map(async (file) => ({
    file, bytes: await readFile(new URL(file, root)),
  })));
  const dist = new URL('dist/', root);
  await rm(dist, { recursive: true, force: true });
  await mkdir(new URL('assets/', dist), { recursive: true });
  await Promise.all(contents.map(({ file, bytes }) => writeFile(new URL(file, dist), bytes)));
  console.log(`Prepared ${contents.length} static files → ${fileURLToPath(dist)}`);
}
